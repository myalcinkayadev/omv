-- Behavior of the clipboard history: what is kept, what is skipped as a secret, and the
-- card's rows. Run through clipboard_test.sh with luajit.

local check = dofile(arg[1] .. "/tests/check.lua")
local clipboard = require("clipboard")

local NOW = 1794150000
local TEXT = { "public.utf8-plain-text" }
local function copy(text, app, types, bundle)
  return { text = text, app = app or "Ghostty", bundle = bundle or "com.mitchellh.ghostty", types = types or TEXT }
end
local function kept(history, entry, now) return clipboard.add(history, entry, now or NOW) end

local history = clipboard.new()
check.that("should keep a copied text", kept(history, copy("git status")) and history.items[1].text == "git status")
kept(history, copy("npm test"), NOW + 1)
check.that("should list the newest first", history.items[1].text == "npm test" and history.items[2].text == "git status")
check.that("should not keep the same text twice in a row", not kept(history, copy("npm test"), NOW + 2) and #history.items == 2)

local full = clipboard.new()
for index = 1, 60 do kept(full, copy("item " .. index), NOW + index) end
check.that("should keep at most 50", #full.items == 50 and full.items[1].text == "item 60")

local old = clipboard.new()
kept(old, copy("yesterday"), NOW)
kept(old, copy("today"), NOW + 25 * 3600)
check.that("should drop copies older than 24 hours", #old.items == 1 and old.items[1].text == "today")

local secret = clipboard.new()
check.that("should skip a copy marked concealed",
  not kept(secret, copy("hunter2", "1Password", { "org.nspasteboard.ConcealedType", "public.utf8-plain-text" }, "x")))
check.that("should skip a copy marked transient", not kept(secret, copy("one-time", "App", { "org.nspasteboard.TransientType" }, "x")))
check.that("should skip a copy marked auto-generated", not kept(secret, copy("generated", "App", { "org.nspasteboard.AutoGeneratedType" }, "x")))
check.that("should skip a copy made in a password manager", not kept(secret, copy("hunter2", "1Password", TEXT, "com.1password.1password")))
check.that("should skip a copy made in Keychain Access", not kept(secret, copy("hunter2", "Keychain Access", TEXT, "com.apple.keychainaccess")))

local slack_fixture = "xox" .. "b-" .. string.rep("A", 24)
local shaped = {
  "sk-ant-api03-AbCdEfGhIjKlMnOpQrStUvWx",
  "ghp_AbCdEfGhIjKlMnOpQrStUvWxYz0123456789",
  "github_pat_11ABCDEFG0123456789_abcdefghijklmnop",
  "AKIAIOSFODNN7EXAMPLE",
  slack_fixture,
  "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjMifQ.c2lnbmF0dXJlLXZhbHVl",
  "-----BEGIN OPENSSH PRIVATE KEY-----\nabc\n-----END OPENSSH PRIVATE KEY-----",
  "API_KEY=abc123",
  "export GITHUB_TOKEN=abc123",
  "DB_PASSWORD: s3cret",
  "client_secret = abc",
}
local skipped = 0
for _, text in ipairs(shaped) do
  if not kept(clipboard.new(), copy(text)) then skipped = skipped + 1 else print("    kept: " .. text) end
end
check.that("should skip text shaped like each secret pattern", skipped == #shaped)
check.that("should keep ordinary text that only mentions a password",
  kept(clipboard.new(), copy("Reset your password before the tokens expire")))
check.that("should keep a word that only contains sk-", kept(clipboard.new(), copy("a risk-free change")))
check.that("should skip empty text", not kept(clipboard.new(), copy("   \n")))

local paused = clipboard.new()
paused.paused = true
check.that("should keep nothing while paused", not kept(paused, copy("git log")) and #paused.items == 0)

local cleared = clipboard.new()
kept(cleared, copy("git log"))
clipboard.clear(cleared)
check.that("should forget everything when cleared", #cleared.items == 0)

local shown = clipboard.new()
kept(shown, copy("first line\nsecond line", "Zed", TEXT, "dev.zed.Zed"), NOW - 120)
local rows = clipboard.rows(shown, NOW)
local item
for _, row in ipairs(rows) do if row.id == "1" then item = row end end
check.that("should show a copy's first line", item and item.label == "first line")
check.that("should show a copy's app and age", item and item.hint == "Zed · 2m ago")
check.that("should offer Pause history first", rows[1].id == "pause")
check.that("should offer Resume history while paused", (function()
  shown.paused = true
  return clipboard.rows(shown, NOW)[1].id == "resume"
end)())
check.that("should offer Clear history", rows[2].id == "clear")

check.finish()
