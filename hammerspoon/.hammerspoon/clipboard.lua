-- The clipboard history: the text and images you copied recently, newest first, kept in
-- memory only.
-- Secrets are never kept: copies password managers mark as concealed, copies made while a
-- password manager is in front, and text shaped like a key or token.
-- Has no Hammerspoon dependency, so the Lua tests can run it with luajit.

local clipboard = {}

local MAX_ITEMS = 50
-- Images are kept apart from the text copies, and fewer, since each holds a picture.
local MAX_IMAGES = 20
local MAX_AGE = 24 * 3600
local LABEL_CHARACTERS = 80

-- The marks password managers put on a copy, per nspasteboard.org: don't record it.
local SKIPPED_TYPES = {
  ["org.nspasteboard.ConcealedType"] = true,
  ["org.nspasteboard.TransientType"] = true,
  ["org.nspasteboard.AutoGeneratedType"] = true,
}

-- Copies made while one of these is in front are never kept.
local PASSWORD_MANAGERS = {
  ["com.1password.1password"] = true,
  ["com.agilebits.onepassword7"] = true,
  ["com.bitwarden.desktop"] = true,
  ["com.apple.Passwords"] = true,
  ["com.apple.keychainaccess"] = true,
}

-- Keys and tokens with a known shape. The frontier keeps "risk-free" from looking like "sk-".
local SECRET_SHAPES = {
  { "%f[%w]sk%-[%w_%-]+", 20 },
  { "%f[%w]gh[pousr]_%w+", 20 },
  { "%f[%w]github_pat_[%w_]+", 20 },
  { "%f[%w]AKIA[%u%d]+", 20 },
  { "%f[%w]xox[abprs]%-[%w%-]+", 15 },
  { "%f[%w]eyJ[%w_%-]+%.[%w_%-]+%.[%w_%-]+", 20 },
  { "%-%-%-%-%-BEGIN [%u ]*PRIVATE KEY%-%-%-%-%-", 1 },
}

-- A line that sets one, as in a .env file: API_KEY=…, export GITHUB_TOKEN=…, DB_PASSWORD: …
local SECRET_NAMES = { "KEY", "TOKEN", "SECRET", "PASSWORD", "PASSWD" }

local function setsSecret(line)
  local upper = line:upper():gsub("^%s*EXPORT%s+", "")
  for _, name in ipairs(SECRET_NAMES) do
    if upper:match("^%s*[%u%d_%.%-]*" .. name .. "[%u%d_]*%s*[=:]%s*%S") then return true end
  end
  return false
end

function clipboard.isSecret(text)
  for _, shape in ipairs(SECRET_SHAPES) do
    local found = text:match(shape[1])
    if found and #found >= shape[2] then return true end
  end
  for line in text:gmatch("[^\n]+") do
    if setsSecret(line) then return true end
  end
  return false
end

local function marked(types)
  for _, kind in ipairs(types or {}) do
    if SKIPPED_TYPES[kind] then return true end
  end
  return false
end

function clipboard.new()
  return { items = {}, paused = false }
end

local function prune(history, now)
  local kept, texts, images = {}, 0, 0
  for _, item in ipairs(history.items) do
    local fresh = now - item.copied <= MAX_AGE
    if fresh and item.image and images < MAX_IMAGES then
      images = images + 1
      kept[#kept + 1] = item
    elseif fresh and not item.image and texts < MAX_ITEMS then
      texts = texts + 1
      kept[#kept + 1] = item
    end
  end
  history.items = kept
end

-- copy.image = { fingerprint, width, height, preview }: the same fingerprint is the same
-- picture, and preview is a small data: URL for the card.
local function addImage(history, copy, now)
  local newest = history.items[1]
  if newest and newest.image and newest.image.fingerprint == copy.image.fingerprint then return false end
  table.insert(history.items, 1, { image = copy.image, app = copy.app or "?", copied = now })
  prune(history, now)
  return true
end

-- Keeps a copy, { text or image, app, bundle, types }, unless it's paused, empty, the same
-- as the newest, or a secret. Says whether it was kept.
function clipboard.add(history, copy, now)
  prune(history, now)
  if history.paused or marked(copy.types) or PASSWORD_MANAGERS[copy.bundle] then return false end
  if type(copy.image) == "table" then return addImage(history, copy, now) end
  local text = copy.text
  if type(text) ~= "string" or not text:find("%S") or clipboard.isSecret(text) then return false end
  if history.items[1] and history.items[1].text == text then return false end
  table.insert(history.items, 1, { text = text, app = copy.app or "?", copied = now })
  prune(history, now)
  return true
end

function clipboard.clear(history)
  history.items = {}
end

local function age(seconds)
  if seconds < 60 then return "now" end
  if seconds < 3600 then return math.floor(seconds / 60) .. "m ago" end
  return math.floor(seconds / 3600) .. "h ago"
end

local function firstLine(text)
  local line = text:match("^%s*([^\n]*)"):gsub("%s+$", "")
  if #line > LABEL_CHARACTERS then line = line:sub(1, LABEL_CHARACTERS) .. "…" end
  return line
end

-- Card rows: Pause or Resume, then Clear, then each copy, with its app and age. A copy's
-- id is its place in the history.
function clipboard.rows(history, now)
  local rows = {
    history.paused and { id = "resume", icon = "󰐊", label = "Resume history" }
      or { id = "pause", icon = "󰏤", label = "Pause history" },
    { id = "clear", icon = "󰆴", label = "Clear history" },
  }
  for index, item in ipairs(history.items) do
    local label = item.image and string.format("Image · %d×%d", item.image.width, item.image.height) or firstLine(item.text)
    rows[#rows + 1] = { id = tostring(index), icon = "󰅍", image = item.image and item.image.preview, label = label,
      hint = item.app .. " · " .. age(now - item.copied) }
  end
  return rows
end

return clipboard
